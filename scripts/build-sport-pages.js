#!/usr/bin/env node
/* ============================================================================
   Generates the /scores/<sport>/ routes.

   These are ROUTES, not pages. Each one is a ten-line redirect into
   scores.html with a sport filter pre-applied -- there is exactly one
   scoreboard implementation and exactly one data path. Adding a sport to
   GameTracker and re-running this adds its route; nothing else changes.

       node scripts/build-sport-pages.js

   Keep the list below in step with gametracker.sports. It is deliberately a
   plain list rather than a database read so the generator works offline and
   the generated routes are reviewable in a diff.
   ============================================================================ */

const fs = require('fs');
const path = require('path');

/* [route, sport filter, page title]
   The filter is passed straight to the GameTracker API, which accepts either a
   sport key ('girls-soccer') or a base sport ('soccer' = boys and girls). */
const ROUTES = [
  // base sports — both genders together
  ['football',            'football',            'Football'],
  ['soccer',              'soccer',              'Soccer'],
  ['volleyball',          'volleyball',          'Volleyball'],
  ['basketball',          'basketball',          'Basketball'],
  ['hockey',              'ice-hockey',          'Ice Hockey'],
  ['lacrosse',            'lacrosse',            'Lacrosse'],
  ['baseball',            'baseball',            'Baseball'],
  ['softball',            'softball',            'Softball'],
  ['wrestling',           'wrestling',           'Wrestling'],
  ['field-hockey',        'field-hockey',        'Field Hockey'],
  ['cross-country',       'cross-country',       'Cross Country'],
  ['track',               'track',               'Track & Field'],
  ['indoor-track',        'indoor-track',        'Indoor Track & Field'],
  ['swimming',            'swimming',            'Swimming & Diving'],
  ['tennis',              'tennis',              'Tennis'],
  ['golf',                'golf',                'Golf'],
  ['bowling',             'bowling',             'Bowling'],
  ['gymnastics',          'gymnastics',          'Gymnastics'],
  ['cheer',               'cheer',               'Competitive Cheer'],
  ['skiing',              'skiing',              'Alpine Skiing'],
  ['crew',                'crew',                'Crew'],
  ['flag-football',       'flag-football',       'Flag Football'],

  // gendered routes
  ['boys-soccer',         'boys-soccer',         'Boys Soccer'],
  ['girls-soccer',        'girls-soccer',        'Girls Soccer'],
  ['boys-volleyball',     'boys-volleyball',     'Boys Volleyball'],
  ['girls-volleyball',    'girls-volleyball',    'Girls Volleyball'],
  ['boys-basketball',     'boys-basketball',     'Boys Basketball'],
  ['girls-basketball',    'girls-basketball',    'Girls Basketball'],
  ['boys-hockey',         'boys-ice-hockey',     'Boys Ice Hockey'],
  ['girls-hockey',        'girls-ice-hockey',    'Girls Ice Hockey'],
  ['boys-lacrosse',       'boys-lacrosse',       'Boys Lacrosse'],
  ['girls-lacrosse',      'girls-lacrosse',      'Girls Lacrosse'],
  ['boys-cross-country',  'boys-cross-country',  'Boys Cross Country'],
  ['girls-cross-country', 'girls-cross-country', 'Girls Cross Country'],
  ['boys-track',          'boys-track',          'Boys Track & Field'],
  ['girls-track',         'girls-track',         'Girls Track & Field'],
  ['boys-swimming',       'boys-swimming',       'Boys Swimming & Diving'],
  ['girls-swimming',      'girls-swimming',      'Girls Swimming & Diving'],
  ['boys-tennis',         'boys-tennis',         'Boys Tennis'],
  ['girls-tennis',        'girls-tennis',        'Girls Tennis'],
  ['girls-wrestling',     'girls-wrestling',     'Girls Wrestling'],
  ['bowling-boys',        'boys-bowling',        'Boys Bowling'],
  ['bowling-girls',       'girls-bowling',       'Girls Bowling'],
];

function page(sport, title) {
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>WNY ${title} Scores &amp; Schedule | 5-Star Sports Media</title>
<meta name="description" content="Live scores, schedules and results for Western New York high school ${title.toLowerCase()} — Section VI, Monsignor Martin and more.">
<link rel="canonical" href="https://5starsportsmedia.com/scores.html?sport=${sport}">
<script>
  /* GENERATED by scripts/build-sport-pages.js — do not edit by hand.
     A route, not a page: one scoreboard, one data path, a sport filter.
     Any extra query params the visitor arrived with are carried through. */
  (function () {
    var q = new URLSearchParams(location.search);
    q.set('sport', ${JSON.stringify(sport)});
    location.replace('../../scores.html?' + q.toString());
  })();
</script>
<meta http-equiv="refresh" content="0;url=../../scores.html?sport=${sport}">
</head>
<body>
<p>Redirecting to the WNY ${title} scoreboard…
   <a href="../../scores.html?sport=${sport}">Continue</a>.</p>
</body>
</html>
`;
}

const root = path.join(__dirname, '..', 'scores');
fs.mkdirSync(root, { recursive: true });

/* /scores/ itself is the full scoreboard, unfiltered. */
fs.writeFileSync(path.join(root, 'index.html'), `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<title>WNY High School Scoreboard | 5-Star Sports Media</title>
<link rel="canonical" href="https://5starsportsmedia.com/scores.html">
<script>
  /* GENERATED by scripts/build-sport-pages.js — do not edit by hand. */
  location.replace('../scores.html' + location.search);
</script>
<meta http-equiv="refresh" content="0;url=../scores.html">
</head>
<body><p><a href="../scores.html">WNY High School Scoreboard</a></p></body>
</html>
`);

let n = 0;
for (const [route, sport, title] of ROUTES) {
  const dir = path.join(root, route);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'index.html'), page(sport, title));
  n++;
}
console.log(`Wrote /scores/index.html + ${n} sport routes.`);
